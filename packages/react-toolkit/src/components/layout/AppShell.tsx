import {
  createContext,
  forwardRef,
  useContext,
  useEffect,
  useId,
  useMemo,
  useState,
  useSyncExternalStore,
  type HTMLAttributes,
  type ReactNode,
} from 'react';
import { cx } from '../../utils/cx';
import { Dialog } from '../dialog/Dialog';

/** Screens at least this wide show the sidebar as a column; narrower ones use a drawer. */
const WIDE = '(min-width: 64rem)';

interface AppShellContextValue {
  hasSidebar: boolean;
  navOpen: boolean;
  drawerId: string;
  openNav: () => void;
  closeNav: () => void;
}

const AppShellContext = createContext<AppShellContextValue | null>(null);

/**
 * The surrounding AppShell's navigation state, or `null` outside one. Use it to build your
 * own menu button: `const shell = useAppShell(); shell?.openNav()`.
 */
export function useAppShell() {
  return useContext(AppShellContext);
}

function subscribeWide(onChange: () => void) {
  const query = window.matchMedia(WIDE);
  query.addEventListener('change', onChange);
  return () => query.removeEventListener('change', onChange);
}
const isWide = () => window.matchMedia(WIDE).matches;

export interface AppShellProps extends HTMLAttributes<HTMLDivElement> {
  /** Top bar, usually an `<AppHeader>`. */
  header?: ReactNode;
  /**
   * Side navigation, usually a `<SideNav>`. A column on screens 64rem (1024px) and wider; on
   * narrower screens it opens in a drawer from AppHeader's menu button.
   */
  sidebar?: ReactNode;
  /** Bottom tab bar for phones, usually a `<MobileTabBar>`. */
  tabBar?: ReactNode;
  /** Page content, rendered in `<main>`. */
  children?: ReactNode;
  /** Text of the skip link, the first thing keyboard users reach. Default `'Skip to main content'`. */
  skipLinkLabel?: string;
  /** Heading of the navigation drawer on narrow screens. Default `'Menu'`. */
  navTitle?: ReactNode;
  /** Id of the `<main>` element (the skip link's target). Generated by default. */
  mainId?: string;
}

/**
 * The frame of an app: a skip link, header, sidebar (or drawer) and main content, with the
 * matching landmarks. Put page content in `children`.
 */
export const AppShell = forwardRef<HTMLDivElement, AppShellProps>(function AppShell(
  {
    header,
    sidebar,
    tabBar,
    children,
    skipLinkLabel = 'Skip to main content',
    navTitle = 'Menu',
    mainId,
    className,
    ...rest
  },
  ref,
) {
  const id = useId();
  const main = mainId ?? `${id}-main`;
  const drawerId = `${id}-drawer`;
  const [navOpen, setNavOpen] = useState(false);
  // On the server, assume a wide screen: the drawer is closed there anyway.
  const wide = useSyncExternalStore(subscribeWide, isWide, () => true);
  const drawerOpen = navOpen && !wide;

  // Close the drawer when the window becomes wide enough for the sidebar column.
  useEffect(() => {
    const query = window.matchMedia(WIDE);
    const close = (event: MediaQueryListEvent) => {
      if (event.matches) setNavOpen(false);
    };
    query.addEventListener('change', close);
    return () => query.removeEventListener('change', close);
  }, []);

  const hasSidebar = sidebar != null;
  const context = useMemo<AppShellContextValue>(
    () => ({
      hasSidebar,
      navOpen,
      drawerId,
      openNav: () => setNavOpen(true),
      closeNav: () => setNavOpen(false),
    }),
    [hasSidebar, navOpen, drawerId],
  );

  return (
    <AppShellContext.Provider value={context}>
      <div
        {...rest}
        ref={ref}
        className={cx('dawg-app', className)}
        data-has-sidebar={hasSidebar || undefined}
        data-has-tab-bar={tabBar != null || undefined}
      >
        <a
          className="dawg-app__skip"
          href={`#${main}`}
          // Focus <main> directly instead of changing the URL, which would confuse hash routers.
          onClick={(event) => {
            const target = document.getElementById(main);
            if (!target) return;
            event.preventDefault();
            target.focus();
          }}
        >
          {skipLinkLabel}
        </a>
        {header}
        <div className="dawg-app__body">
          {hasSidebar && (
            // Hidden while the drawer shows the same navigation, so it isn't listed twice.
            <div className="dawg-app__sidebar" hidden={drawerOpen || undefined}>
              {sidebar}
            </div>
          )}
          <main id={main} className="dawg-app__main" tabIndex={-1}>
            {children}
          </main>
        </div>
        {tabBar}
        {hasSidebar && (
          <Dialog
            id={drawerId}
            open={drawerOpen}
            onClose={() => setNavOpen(false)}
            title={navTitle}
            placement="start"
            size="sm"
            className="dawg-app__drawer"
          >
            {sidebar}
          </Dialog>
        )}
      </div>
    </AppShellContext.Provider>
  );
});

const MenuIcon = () => (
  <svg
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    strokeWidth={2}
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
  >
    <path d="M4 7h16M4 12h16M4 17h16" />
  </svg>
);

export interface AppHeaderProps extends HTMLAttributes<HTMLElement> {
  /** Logo and app name, usually a link to the home page. */
  brand?: ReactNode;
  /** Content at the end, e.g. a ThemeToggle and an account menu. */
  actions?: ReactNode;
  /** Content between the brand and the actions, e.g. a search field or top links. */
  children?: ReactNode;
  /** Accessible name of the menu button shown on narrow screens. Default `'Open navigation'`. */
  menuLabel?: string;
}

/**
 * The top bar of an AppShell (a `<header>` landmark). On narrow screens it shows a menu
 * button that opens the sidebar in a drawer.
 */
export const AppHeader = forwardRef<HTMLElement, AppHeaderProps>(function AppHeader(
  { brand, actions, children, menuLabel = 'Open navigation', className, ...rest },
  ref,
) {
  const shell = useAppShell();
  return (
    <header {...rest} ref={ref} className={cx('dawg-app-header', className)}>
      {shell?.hasSidebar && (
        <button
          type="button"
          className="dawg-app-header__menu"
          aria-label={menuLabel}
          title={menuLabel}
          aria-haspopup="dialog"
          aria-expanded={shell.navOpen}
          aria-controls={shell.navOpen ? shell.drawerId : undefined}
          onClick={shell.openNav}
        >
          <MenuIcon />
        </button>
      )}
      {brand && <div className="dawg-app-header__brand">{brand}</div>}
      {children && <div className="dawg-app-header__content">{children}</div>}
      {actions && <div className="dawg-app-header__actions">{actions}</div>}
    </header>
  );
});
