export type DesignTokenName = (typeof DESIGN_TOKENS)[number];
export type ComponentTokenName = (typeof COMPONENT_TOKENS)[number];
/** Any token a theme can set, e.g. `'color-primary-solid'` or `'button-radius'`. */
export type ThemeTokenName = DesignTokenName | ComponentTokenName;
/** A set of token values; each value is any valid CSS value for that property. */
export type ThemeTokens = Partial<Record<ThemeTokenName, string>>;
